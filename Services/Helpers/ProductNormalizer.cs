    // Убираем способ приготовления и лишние детали
    private static readonly (Regex Pattern, string Replace)[] _preprocessRules =
    [
        // Скобочные уточнения — чаще всего мусор: "курица (охл.)", "молоко (3,2%)"
        (new Regex(@"\([^)]*\)", RegexOptions.Compiled), ""),
        // Числа с % — "молоко 3.2%"
        (new Regex(@"\b\d+[.,]?\d*\s*%", RegexOptions.Compiled), ""),
        // "без X" — "без кожи", "без косточки"
        (new Regex(@"\bбез\s+\S+", RegexOptions.Compiled | RegexOptions.IgnoreCase), ""),
        // "для X" — "для запекания", "для жарки"
        (new Regex(@"\bдля\s+\w+", RegexOptions.Compiled | RegexOptions.IgnoreCase), ""),
        // "не менее X г", "около X мл" и прочие количества
        (new Regex(@"\b(около|не менее|примерно|по)\s+[\d,.\s]*(г|кг|мл|л|шт)?\b",
            RegexOptions.Compiled | RegexOptions.IgnoreCase), ""),
        // Лишние пробелы
        (new Regex(@"\s{2,}", RegexOptions.Compiled), " "),
    ];

    private static string Preprocess(string input)
    {
        var s = input.ToLower().Trim();

        // Убираем перечисленные слова-мусор (граница слова)
        foreach (var word in _stripWords)
            s = Regex.Replace(s, $@"\b{Regex.Escape(word)}\b", " ", RegexOptions.IgnoreCase);

        // Применяем regex-правила предобработки
        foreach (var (pattern, replace) in _preprocessRules)
            s = pattern.Replace(s, replace);

        return s.Trim();
    }

