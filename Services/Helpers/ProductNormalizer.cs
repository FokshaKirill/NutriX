    // ЭТАП 3. Точечные исключения (слова-ловушки, омонимы и т.п.)
    // Применяются ДО regex-правил, т.к. regex может дать неверный результат
    // ════════════════════════════════════════════════════════════════════

    private static readonly Dictionary<string, string> _exceptions =
        new(StringComparer.OrdinalIgnoreCase)
        {
            // «масло» без уточнения — сливочное в выпечке, подсолнечное в жарке;
            // в рецептах с 1000.menu чаще оливковое/подсолнечное — ставим подсолнечное
            ["масло"]        = "Масло подсолнечное",
            // «перец» — в контексте овощей это болгарский, как специя — чёрный;
            // неоднозначно → оставляем чёрный (специи встречаются чаще)
            ["перец"]        = "Перец чёрный молотый",
            // «мука» без уточнения
            ["мука"]         = "Мука пшеничная",
            // «паста» — в итальянских рецептах это макароны
            ["паста"]        = "Макароны спагетти",
            // «лист» — чаще всего лавровый
            ["лист"]         = "Лавровый лист",
        };

    // ════════════════════════════════════════════════════════════════════
    // Публичный API
    // ════════════════════════════════════════════════════════════════════

    /// <summary>
    /// Нормализует сырое название ингредиента из рецепта
    /// в каноническое имя из PDB.
    /// Возвращает null, если ничего не распознано (создавай продукт-заглушку).
    /// </summary>
    public static string? Normalize(string rawName)
    {
        if (string.IsNullOrWhiteSpace(rawName)) return null;

        var cleaned = Preprocess(rawName);

        // Этап 3: точечные исключения по очищенной строке
        if (_exceptions.TryGetValue(cleaned, out var exc)) return exc;

        // Этап 2: regex-правила
        foreach (var (pattern, canonical) in _rules)
            if (pattern.IsMatch(cleaned))
                return canonical;

        return null; // не распознан
    }

    // helper — компилируем regex сразу при старте
    private static Regex Rx(string pattern) =>
        new(pattern, RegexOptions.Compiled | RegexOptions.IgnoreCase);
