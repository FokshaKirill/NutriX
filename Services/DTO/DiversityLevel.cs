using Domain.Enums;

namespace Services.DTO
{
    /// <summary>
    /// Степень разнообразия меню — определяет кулдаун повторения рецептов.
    /// Значение enum = количество дней между повторами одного рецепта.
    /// </summary>
    public enum DiversityLevel
    {
        /// <summary>Слабое разнообразие: рецепт не повторяется 1 день.</summary>
        Low    = 1,
 
        /// <summary>Нормальное разнообразие: рецепт не повторяется 3 дня (по умолчанию).</summary>
        Normal = 3,
 
        /// <summary>Высокое разнообразие: рецепт не повторяется 5 дней.</summary>
        High   = 5
    }
}